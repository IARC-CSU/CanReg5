#!/usr/bin/env python3
"""
convert_docs_to_md.py
Converts CanReg5 LaTeX/LyX documentation into a clean, structured folder of GitHub-Flavored Markdown files.
Option C: Generates doc/instructions/ with full table of contents, image mapping, and chapter navigation.
"""

import os
import re
import shutil
import subprocess

SRC_DIR = "doc/CanReg5-Instructions"
DEST_DIR = "doc/instructions"
IMG_DEST_DIR = os.path.join(DEST_DIR, "images")
TEX_FILE = os.path.join(SRC_DIR, "CanReg5-Instructions.tex")
CHANGELOG_FILE = "changelog.txt"

CHAPTER_NAMES = [
    (1, "what-is-canreg", "What is CanReg?"),
    (2, "software-installation", "Software Installation"),
    (3, "first-launch", "First Launch"),
    (4, "start", "Start & Navigation"),
    (5, "data-entry", "Data Entry"),
    (6, "analysis", "Analysis & Reports"),
    (7, "management", "Management & Quality Control"),
    (8, "faq", "Frequently Asked Questions"),
    (9, "known-issues", "Known Issues"),
    (10, "migrating-from-canreg4", "Migrating from CanReg4"),
    (11, "advanced-database-management", "Advanced Database Management"),
    (12, "table-builder-technical-details", "Technical Details on the Table Builder"),
    (13, "third-party-tools", "Third Party Tools"),
    (14, "scripts", "Scripts & Utilities"),
    (15, "about", "About & Acknowledgments"),
    (16, "changelog", "Changelog"),
]

def build_image_map(src_dir):
    """Build a map of base image names to actual filenames in src_dir."""
    files = os.listdir(src_dir)
    image_map = {}
    for f in files:
        if f.lower().endswith(('.png', '.jpg', '.jpeg', '.gif', '.svg', '.pdf')) and not f.startswith("CanReg5-Instructions.pdf"):
            base, ext = os.path.splitext(f)
            # Prefer png over other extensions if both exist
            if base not in image_map or ext.lower() == '.png':
                image_map[base] = f
            image_map[f] = f
    return image_map

def clean_markdown(md_text, image_map):
    # Remove empty spans generated by pandoc
    md_text = re.sub(r'<span id="[^"]*" data-label="[^"]*"></span>', '', md_text)

    # Function to resolve image references
    def replace_md_img(m):
        alt = m.group(1)
        src = m.group(2).strip()
        if src.startswith("http://") or src.startswith("https://") or src.startswith("images/"):
            return m.group(0)
        # Look up in image map
        resolved = image_map.get(src) or image_map.get(os.path.basename(src))
        if not resolved:
            # Try without extension
            base, _ = os.path.splitext(src)
            resolved = image_map.get(base)
        if resolved:
            return f"![{alt}](images/{resolved})"
        return f"![{alt}]({src})"

    def replace_html_img(m):
        pre = m.group(1)
        src = m.group(2).strip()
        post = m.group(3)
        if src.startswith("http://") or src.startswith("https://") or src.startswith("images/"):
            return m.group(0)
        resolved = image_map.get(src) or image_map.get(os.path.basename(src))
        if not resolved:
            base, _ = os.path.splitext(src)
            resolved = image_map.get(base)
        if resolved:
            return f'<img {pre}src="images/{resolved}"{post}>'
        return m.group(0)

    md_text = re.sub(r'!\[([^\]]*)\]\(([^)]+)\)', replace_md_img, md_text)
    md_text = re.sub(r'<img\s+([^>]*?)src="([^"]+)"([^>]*)>', replace_html_img, md_text)

    # Clean multiple blank lines
    md_text = re.sub(r'\n{3,}', '\n\n', md_text)
    return md_text.strip() + '\n'

def main():
    os.makedirs(IMG_DEST_DIR, exist_ok=True)
    image_map = build_image_map(SRC_DIR)

    # 1. Copy all images to images/
    print("Copying images to doc/instructions/images/...")
    copied_count = 0
    for f in os.listdir(SRC_DIR):
        if f.lower().endswith(('.png', '.jpg', '.jpeg', '.gif', '.svg', '.pdf')) and not f.startswith("CanReg5-Instructions.pdf"):
            src_path = os.path.join(SRC_DIR, f)
            dest_path = os.path.join(IMG_DEST_DIR, f)
            shutil.copy2(src_path, dest_path)
            copied_count += 1
    print(f"Copied {copied_count} images.")

    # 2. Read full LaTeX source
    with open(TEX_FILE, 'r', encoding='utf-8', errors='replace') as f:
        tex_content = f.read()

    # Split by \chapter{...}
    pattern = re.compile(r'\\chapter\{([^}]+)\}')
    matches = list(pattern.finditer(tex_content))

    chapters_data = []
    for idx, match in enumerate(matches):
        raw_title = match.group(1)
        # Strip indexing commands and formatting from title
        clean_title = re.sub(r'\\index\{[^}]+\}', '', raw_title)
        clean_title = re.sub(r'\\textsf\{\\textbf\{([^}]+)\}\}', r'\1', clean_title).strip()

        start_pos = match.start()
        end_pos = matches[idx + 1].start() if idx + 1 < len(matches) else len(tex_content)
        chunk = tex_content[start_pos:end_pos]
        chapters_data.append((idx + 1, clean_title, chunk))

    # 3. Convert each chapter
    print(f"Converting {len(chapters_data)} chapters to Markdown...")
    converted_files = []

    for idx, clean_title, chunk in chapters_data:
        num_str = f"{idx:02d}"
        slug = CHAPTER_NAMES[idx - 1][1] if idx - 1 < len(CHAPTER_NAMES) else f"chapter-{idx}"
        display_title = CHAPTER_NAMES[idx - 1][2] if idx - 1 < len(CHAPTER_NAMES) else clean_title
        filename = f"{num_str}-{slug}.md"
        filepath = os.path.join(DEST_DIR, filename)

        # Special handling for Chapter 16 (Changelog)
        if idx == 16 or "changelog" in slug.lower():
            changelog_text = ""
            if os.path.exists(CHANGELOG_FILE):
                with open(CHANGELOG_FILE, 'r', encoding='utf-8', errors='replace') as cf:
                    changelog_text = cf.read().strip()

            final_md = (
                f"# 16. {display_title}\n\n"
                "The complete version history for CanReg5 is maintained in [`changelog.txt`](../../changelog.txt) "
                "and can also be viewed as [HTML](../../changelog.html).\n\n"
                "```text\n"
                f"{changelog_text}\n"
                "```\n"
            )
            converted_files.append((filename, display_title, idx, final_md))
            print(f"  Processed (direct): {filename} ({display_title})")
            continue

        # Pre-clean chunk before pandoc
        # Remove trailing document macros and printindex
        chunk_clean = re.sub(r'\\printindex', '', chunk)
        chunk_clean = re.sub(r'\\end\{document\}', '', chunk_clean)

        # Run pandoc
        proc = subprocess.Popen(
            ["pandoc", "-f", "latex", "-t", "gfm"],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True
        )
        stdout, stderr = proc.communicate(input=chunk_clean)
        if proc.returncode != 0:
            print(f"Warning converting chapter {idx}: {stderr}")
            continue

        cleaned_md = clean_markdown(stdout, image_map)

        # Standardize top-level title
        lines = cleaned_md.split('\n')
        header_set = False
        new_lines = []
        for line in lines:
            if not header_set and line.startswith('#'):
                new_lines.append(f"# {idx}. {display_title}")
                header_set = True
            else:
                new_lines.append(line)
        if not header_set:
            new_lines.insert(0, f"# {idx}. {display_title}\n")

        final_md = '\n'.join(new_lines).strip() + '\n'
        converted_files.append((filename, display_title, idx, final_md))
        print(f"  Converted: {filename} ({display_title})")

    # 4. Add header and footer navigation links to each chapter
    total_chapters = len(converted_files)
    for i, (filename, display_title, idx, content) in enumerate(converted_files):
        filepath = os.path.join(DEST_DIR, filename)

        nav_links = []
        if i > 0:
            prev_file, prev_title, prev_idx, _ = converted_files[i - 1]
            nav_links.append(f"[← Previous: {prev_idx}. {prev_title}]({prev_file})")
        nav_links.append("[Table of Contents](README.md)")
        if i < total_chapters - 1:
            next_file, next_title, next_idx, _ = converted_files[i + 1]
            nav_links.append(f"[Next: {next_idx}. {next_title} →]({next_file})")

        header_nav = " · ".join(nav_links)
        footer_nav = " | ".join(nav_links)

        full_content = (
            f"*{header_nav}*\n\n"
            "---\n\n"
            f"{content.strip()}\n\n"
            "---\n\n"
            f"*{footer_nav}*\n"
        )

        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(full_content)

    # 5. Generate README.md (Table of Contents)
    print("Generating doc/instructions/README.md...")
    toc_lines = [
        "# CanReg5 User Instructions & Handbook\n",
        "Welcome to the official documentation and user handbook for **CanReg5** — the open-source tool for cancer registries to input, store, check, and analyze cancer data.\n",
        "> **Note:** This documentation is available in multiple formats:\n"
        "> - **Online Markdown:** Browse chapters directly below on GitHub.\n"
        "> - **Offline PDF:** A complete compiled PDF version with figures and index is available at [`doc/CanReg5-Instructions.pdf`](../CanReg5-Instructions.pdf) and bundled in the release zip files.\n"
        "> - **Source LyX/LaTeX:** Available in [`doc/CanReg5-Instructions/`](../CanReg5-Instructions/).\n",
        "## Table of Contents\n"
    ]
    for filename, title, num, _ in converted_files:
        toc_lines.append(f"{num}. [{title}]({filename})")

    toc_lines.append("\n---\n")
    toc_lines.append("### Project & Community Links\n")
    toc_lines.append("- **Repository:** [https://github.com/IARC-CSU/CanReg5](https://github.com/IARC-CSU/CanReg5)\n")
    toc_lines.append("- **Official Website:** [https://www.iarc.who.int/](https://www.iarc.who.int/)\n")
    toc_lines.append("- **Bug Reports & Issues:** [https://github.com/IARC-CSU/CanReg5/issues](https://github.com/IARC-CSU/CanReg5/issues)\n")
    toc_lines.append("- **Email:** [canreg@iarc.who.int](mailto:canreg@iarc.who.int)\n")

    with open(os.path.join(DEST_DIR, "README.md"), 'w', encoding='utf-8') as f:
        f.write('\n'.join(toc_lines) + '\n')

    print(f"Successfully generated all {total_chapters} chapters and README.md in {DEST_DIR}/")

if __name__ == "__main__":
    main()
